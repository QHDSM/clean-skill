#!/usr/bin/env python3
"""End-to-end check of the whole chain, on real files, in a throwaway directory.

    python e2e_check.py --drive C:

scan -> plan.json -> dry-run -> --go -> RECYCLED -> --undo -> byte-identical.

Every step asserts something a unit test cannot: that this machine's volume
really recycles, that the preview accepts a plan built from a real scan, that
the audit log alone is enough to put the objects back, and that what came back
is the same bytes. Nothing outside the directory this script creates is read or
written; the directory is removed at the end unless --keep is given.

Exit codes: 0 all checks passed, 1 a check failed, 2 the environment cannot run
the check (no volume with a Recycle Bin, wrong drive for the temp directory).
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
PYTHON = sys.executable


def run(script, *args, timeout=300):
    return subprocess.run([PYTHON, str(HERE / script), *args],
                          capture_output=True, text=True, timeout=timeout)


def parse(stdout):
    try:
        return json.loads(stdout)
    except json.JSONDecodeError:
        return None


class Checker:
    def __init__(self):
        self.checks = []
        self.ok = True

    def check(self, name, condition, detail=''):
        self.checks.append({'check': name, 'ok': bool(condition), 'detail': detail})
        if not condition:
            self.ok = False
        return condition


def digest(path):
    hasher = hashlib.sha256()
    with open(path, 'rb') as fh:
        for block in iter(lambda: fh.read(65536), b''):
            hasher.update(block)
    return hasher.hexdigest()


def drive_of(path):
    return os.path.splitdrive(os.path.abspath(str(path)))[0].upper()


def make_workdir(drive):
    base = os.environ.get('TEMP') or os.environ.get('TMP')
    if not base or drive_of(base) != drive.upper():
        return None
    root = Path(base) / f'disk-cleanup-e2e-{secrets.token_hex(4)}'
    root.mkdir()
    return root


def build_plan(scan_report, root):
    """Pick the probe file and the nested directory out of a real scan report."""
    wanted_file = str(root / 'probe.bin')
    wanted_dir = str(root / 'nested')
    file_row = next((row for row in scan_report.get('largest_files') or []
                     if os.path.normcase(row['path']) == os.path.normcase(wanted_file)), None)
    dir_row = next((row for row in scan_report.get('largest_directories') or []
                    if os.path.normcase(row['path']) == os.path.normcase(wanted_dir)), None)
    if not file_row or not dir_row:
        return None
    targets = [
        {'path': file_row['path'], 'action': 'trash', 'risk': 'safe',
         'reason': 'e2e probe file created by e2e_check.py',
         'evidence': {'fingerprint': file_row['fingerprint'],
                      'size_bytes': file_row['logical_bytes']}},
        {'path': dir_row['path'], 'action': 'trash', 'risk': 'safe',
         'reason': 'e2e nested directory created by e2e_check.py',
         'evidence': {'fingerprint': dir_row['fingerprint']}},
    ]
    return {'schema': 'disk-cleanup-plan/v1', 'generated_unix': 0,
            'authorization': {'scope': [str(root)], 'excluded': []},
            'targets': targets,
            'note': 'generated by e2e_check.py; deleted and restored immediately'}


def main(argv=None):
    parser = argparse.ArgumentParser(description='Real scan, recycle and undo in a temp directory.')
    parser.add_argument('--drive', default='C:')
    parser.add_argument('--keep', action='store_true', help='leave the work directory in place')
    parser.add_argument('--json', action='store_true')
    args = parser.parse_args(argv)
    drive = args.drive.rstrip('\\').upper()
    if len(drive) == 1:
        drive += ':'
    result = Checker()

    def emit(code):
        payload = {'ok': result.ok, 'drive': drive, 'checks': result.checks}
        if args.json:
            print(json.dumps(payload, ensure_ascii=False, indent=2))
        else:
            for row in result.checks:
                print(f"  [{'ok ' if row['ok'] else 'FAIL'}] {row['check']}"
                      + (f" -- {row['detail']}" if row['detail'] else ''))
            print('result:', 'OK' if result.ok else 'FAILED')
        return code

    selfcheck = run('recycle_selfcheck.py', '--drive', drive)
    if not result.check('volume can recycle and restore', selfcheck.returncode == 0,
                        (selfcheck.stdout or selfcheck.stderr).strip().splitlines()[-1]
                        if (selfcheck.stdout or selfcheck.stderr).strip() else ''):
        return emit(2)

    workdir = make_workdir(drive)
    if not workdir:
        result.check('a temp directory on the target drive', False,
                     f'TEMP is not on {drive}; pass a drive whose temp you can write')
        return emit(2)
    result.check('work directory created', True, str(workdir))

    try:
        (workdir / 'nested').mkdir()
        (workdir / 'probe.bin').write_bytes(bytes(range(256)) * 8)
        (workdir / 'nested' / 'inner.bin').write_bytes(b'e2e-inner' * 128)
        digests = {path: digest(path) for path in
                   (workdir / 'probe.bin', workdir / 'nested' / 'inner.bin')}

        scan_out = workdir / 'scan.json'
        scanned = run('scan.py', str(workdir), '--format', 'json', '--top', '50',
                      '--output', str(scan_out))
        scan_report = parse(scan_out.read_text(encoding='utf-8')) if scan_out.exists() else None
        if not result.check('scan produced a report', scanned.returncode == 0 and bool(scan_report),
                            (scanned.stderr or '').strip()[:200]):
            return emit(1)

        plan = build_plan(scan_report, workdir)
        if not result.check('scan report contains both candidates', plan is not None):
            return emit(1)
        plan_path = workdir / 'plan.json'
        plan_path.write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding='utf-8')

        preview = run('clean.py', '--plan', str(plan_path), '--json')
        preview_report = parse(preview.stdout)
        refused = [r for r in (preview_report or {}).get('results', [])
                   if r.get('result') == 'refused']
        result.check('preview accepts the plan', preview.returncode == 0 and not refused,
                     '; '.join(f"{r['path']}: {(r.get('detail') or '')[:80]}" for r in refused))

        executed = run('clean.py', '--plan', str(plan_path), '--go', '--json')
        report = parse(executed.stdout)
        if not result.check('--go returned a report', report is not None,
                            (executed.stderr or '').strip()[:300]):
            return emit(1)

        results = report.get('results') or []
        result.check('two targets were handled', len(results) == 2, f'got {len(results)}')
        statuses = [((row.get('recycle') or {}).get('status')) for row in results]
        result.check('every target reports RECYCLED',
                     statuses and all(status == 'RECYCLED' for status in statuses),
                     ', '.join(str(status) for status in statuses))
        proofs = [((row.get('recycle') or {}).get('proof') or {}).get('final_path')
                  for row in results]
        result.check('every proof points into $RECYCLE.BIN',
                     proofs and all(path and '$recycle.bin' in path.lower() for path in proofs),
                     '; '.join(str(path) for path in proofs))
        result.check('nothing is left at the original paths',
                     not (workdir / 'probe.bin').exists() and not (workdir / 'nested').exists())

        audit = report.get('audit_log')
        if not result.check('an audit log was written', bool(audit) and os.path.exists(audit), str(audit)):
            return emit(1)

        undone = run('clean.py', '--undo', audit, '--json')
        undo_report = parse(undone.stdout)
        if not result.check('--undo returned a report', undo_report is not None,
                            (undone.stderr or '').strip()[:300]):
            return emit(1)
        undo_results = undo_report.get('results') or []
        result.check('both objects restored',
                     len(undo_results) == 2 and all(row.get('result') == 'restored'
                                                    for row in undo_results),
                     ', '.join(str(row.get('result')) for row in undo_results))
        result.check('restored identity verified where recorded',
                     all(row.get('verified') is not False for row in undo_results),
                     ', '.join(str(row.get('verified')) for row in undo_results))

        restored_ok = True
        for path, expected in digests.items():
            if not path.exists() or digest(path) != expected:
                restored_ok = False
        result.check('restored bytes match what was written', restored_ok)
        result.check('nested directory contents came back',
                     (workdir / 'nested' / 'inner.bin').exists())
    finally:
        if args.keep:
            result.check('work directory kept', True, str(workdir))
        else:
            shutil.rmtree(workdir, ignore_errors=True)
            result.check('work directory removed', not workdir.exists())

    return emit(0 if result.ok else 1)


if __name__ == '__main__':
    sys.exit(main())
